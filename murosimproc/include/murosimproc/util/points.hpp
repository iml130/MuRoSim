#ifndef MUROSIMPROC_UTIL_POINTS_HPP_
#define MUROSIMPROC_UTIL_POINTS_HPP_

#include <assert.h>
#include "murosim/random/random_generator.hpp"
#include <Eigen/Geometry>

namespace murosimproc::util::points
{

/// Appends `number_of_points` uniformly-distributed random points inside the axis-aligned rectangle spanned by `point1` and `point2` to `points`.
/// @param seed Seeds a new random generator; two calls with the same seed and arguments produce the same points.
void createRandomPointsRectangleUniform(std::vector<Eigen::Vector2f> &points, const murosim::random::RandomGenerator::result_type seed, const Eigen::Vector2f point1, const Eigen::Vector2f point2, const size_t number_of_points);
/// Same as the seed-overload, drawing from the caller-owned `random_generator` (advances its state).
void createRandomPointsRectangleUniform(std::vector<Eigen::Vector2f> &points, murosim::random::RandomGenerator &random_generator, const Eigen::Vector2f point1, const Eigen::Vector2f point2, const size_t number_of_points);
/// Appends points on a jittered hexagonal (staggered-row) lattice covering the rectangle spanned by `point1` and `point2` to `points`.
/// @param spacing Distance between neighbouring points on the same row (metres, must be > 0).
/// @param noise Amplitude of the per-point random jitter added to each lattice position (metres, must be >= 0).
/// @param seed Seeds a new random generator; two calls with the same seed and arguments produce the same points.
void createRandomPointsRectangleHexagon(std::vector<Eigen::Vector2f> &points, const murosim::random::RandomGenerator::result_type seed, const Eigen::Vector2f point1, const Eigen::Vector2f point2, const float spacing, const float noise);
/// Same as the seed-overload, drawing from the caller-owned `random_generator` (advances its state).
void createRandomPointsRectangleHexagon(std::vector<Eigen::Vector2f> &points, murosim::random::RandomGenerator &random_generator, const Eigen::Vector2f point1, const Eigen::Vector2f point2, const float spacing, const float noise);
/// Appends points generated by Poisson-disk sampling (Bridson's algorithm) inside the rectangle spanned by `point1` and `point2` to `points`.
/// Each point is assigned its own exclusion radius drawn uniformly from `[min_distance, max_distance]`; any two points respect the larger of their two radii.
/// @param min_distance Minimum allowed spacing between points (metres, must be > 0).
/// @param max_distance Maximum per-point exclusion radius (metres, must be >= `min_distance`).
/// @param k Number of candidate points tried per active sample before it is retired (must be > 0).
/// @param seed Seeds a new random generator; two calls with the same seed and arguments produce the same points.
void createRandomPointsRectanglePoissonDisk(std::vector<Eigen::Vector2f> &points, const murosim::random::RandomGenerator::result_type seed, const Eigen::Vector2f point1, const Eigen::Vector2f point2, const float min_distance, const float max_distance, const size_t k = 30);
/// Same as the seed-overload, drawing from the caller-owned `random_generator` (advances its state).
void createRandomPointsRectanglePoissonDisk(std::vector<Eigen::Vector2f> &points, murosim::random::RandomGenerator &random_generator, const Eigen::Vector2f point1, const Eigen::Vector2f point2, const float min_distance, const float max_distance, const size_t k = 30);
/// Shuffles `points` and truncates it in place to a random size in `[min_number_of_points, max_number_of_points]`. Leaves `points` unchanged if it already has at most that many elements.
/// @param seed Seeds a new random generator; two calls with the same seed and input produce the same result.
void choiceRandomPointsMinMax(std::vector<Eigen::Vector2f> &points, const murosim::random::RandomGenerator::result_type seed, const size_t min_number_of_points, const size_t max_number_of_points);
/// Same as the seed-overload, drawing from the caller-owned `random_generator` (advances its state).
void choiceRandomPointsMinMax(std::vector<Eigen::Vector2f> &points, murosim::random::RandomGenerator &random_generator, const size_t min_number_of_points, const size_t max_number_of_points);

} // namespace murosimproc::util::points

#endif // MUROSIMPROC_UTIL_POINTS_HPP_
