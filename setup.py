"""
Top-level setup script for building all murosim Python packages.

Builds the murosimpy, murosimrlpy and murosimprocpy extension modules in a
single CMake invocation (see cmake_build.py). This is the only supported
Python entry point; the individual packages have no setup.py of their own.

Environment variables:
    MUROSIM_NATIVE_ARCH: Set to "1" to enable -march=native optimization.
    CMAKE_BUILD_PARALLEL_LEVEL: Number of parallel build jobs.
"""

import os
import sys
from pathlib import Path

# Add the directory containing this file to sys.path for cmake_build import
sys.path.insert(0, str(Path(__file__).parent.resolve()))

from cmake_build import CMakeExtension, CMakeBuild
from setuptools import setup

# PEP 561 stub-only packages (stubs/<module>-stubs/**/*.pyi), generated by
# tools/generate_stubs.py. The extension modules themselves are top-level .so
# files; the stubs are what type checkers and IDEs read.
STUBS_DIR = Path(__file__).parent / "stubs"
stub_packages = sorted(
    str(d.relative_to(STUBS_DIR)).replace(os.sep, ".")
    for d in STUBS_DIR.rglob("*")
    # only the <module>-stubs trees; setuptools also writes its egg-info here
    if d.is_dir() and d.relative_to(STUBS_DIR).parts[0].endswith("-stubs")
)

setup(
    packages=stub_packages,
    package_dir={"": "stubs"},
    package_data={p: ["*.pyi"] for p in stub_packages},
    ext_modules=[
        CMakeExtension("murosimpy"),
        CMakeExtension("murosimrlpy"),
        CMakeExtension("murosimprocpy"),
    ],
    cmdclass={"build_ext": CMakeBuild},
    zip_safe=False,
)
